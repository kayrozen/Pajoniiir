#!/usr/bin/env python3
"""Generate the polyphase windowed-sinc table of audio_resampler.c (JC1060).

16 taps, Kaiser window, cutoff as a fraction of the source rate, 32 phases
plus the closing phase (the resampler interpolates linearly between two
adjacent phases). Every phase is normalised to unity DC gain.

Usage: python3 tools/audio/gen_resampler_sinc_table.py > \
    firmware/main-deck-jc1060/components/audio_engine/audio_resampler_sinc_table.h
"""
import math

TAPS = 16
PHASES = 32
CUTOFF = 0.45  # x source rate: 19.8 kHz at 44.1 kHz
BETA = 7.0


def bessel_i0(x):
    total = term = 1.0
    for k in range(1, 40):
        term *= (x / 2.0 / k) ** 2
        total += term
    return total


def phase_row(fraction):
    half = TAPS / 2
    row = []
    for k in range(TAPS):
        # Tap k is the source frame (k - (half - 1)) frames after `previous`.
        x = fraction + (half - 1) - k
        if abs(x) >= half:
            row.append(0.0)
            continue
        window = bessel_i0(BETA * math.sqrt(1.0 - (x / half) ** 2)) / bessel_i0(BETA)
        arg = 2.0 * CUTOFF * x
        sinc = 1.0 if abs(x) < 1e-12 else math.sin(math.pi * arg) / (math.pi * arg)
        row.append(2.0 * CUTOFF * sinc * window)
    total = sum(row)
    return [v / total for v in row]


def main():
    print("/* Generated by tools/audio/gen_resampler_sinc_table.py - do not edit.")
    print(f" * {TAPS} taps, Kaiser beta {BETA}, cutoff {CUTOFF} x source rate,")
    print(f" * {PHASES} phases + closing phase, unity DC gain per phase. */")
    print("#pragma once")
    print()
    print(f"#define AUDIO_RESAMPLER_SINC_PHASES {PHASES}u")
    print()
    print("static const float s_resampler_sinc[AUDIO_RESAMPLER_SINC_PHASES + 1u]"
          "[AUDIO_RESAMPLER_TAPS] = {")
    for p in range(PHASES + 1):
        row = phase_row(p / PHASES)
        print("    { " + ", ".join(f"{v:.9e}f" for v in row) + " },")
    print("};")


if __name__ == "__main__":
    main()
