#!/usr/bin/env python3
"""Generate the half-band 2:1 decimation filter of audio_decim2.c (JC1060).

63 taps, Kaiser beta 8.5, unity DC gain. A half-band filter has only the
centre tap (0.5) and the odd taps non-zero, so only the 16 odd taps of one
side are stored. Response at the input rate: flat within 0.0005 dB up to
0.205 fs (19.7 kHz at 96 kHz, 18.1 kHz at 88.2 kHz), at least 85 dB down from
0.295 fs (28.3 / 26.0 kHz), so nothing aliases below 0.205 fs of the output.

Usage: python3 tools/audio/gen_decim2_table.py > \
    firmware/main-deck-jc1060/components/audio_engine/audio_decim2_table.h
"""
import math

L = 16
BETA = 8.5
M = 2 * L - 1


def bessel_i0(x):
    total = term = 1.0
    for k in range(1, 40):
        term *= (x / 2.0 / k) ** 2
        total += term
    return total


def tap(k):
    sinc = 0.5 if k == 0 else math.sin(math.pi * k / 2.0) / (math.pi * k)
    r = k / (M + 1)
    return sinc * bessel_i0(BETA * math.sqrt(1.0 - r * r)) / bessel_i0(BETA)


def main():
    taps = [tap(k) for k in range(-M, M + 1)]
    total = sum(taps)
    odd = [tap(k) / total for k in range(1, M + 1, 2)]
    centre = tap(0) / total
    print("/* Generated by tools/audio/gen_decim2_table.py - do not edit.")
    print(f" * Half-band, {2 * M + 1} taps, Kaiser beta {BETA}, unity DC gain. */")
    print("#pragma once")
    print()
    print(f"#define AUDIO_DECIM2_ODD_TAPS {L}u")
    print(f"#define AUDIO_DECIM2_CENTRE {centre:.9e}f")
    print("/* h[1], h[3], ... h[" + str(M) + "]; h[-k] = h[k], even taps are 0. */")
    print("static const float s_decim2_odd[AUDIO_DECIM2_ODD_TAPS] = {")
    for i in range(0, L, 4):
        print("    " + ", ".join(f"{v:.9e}f" for v in odd[i:i + 4]) + ",")
    print("};")


if __name__ == "__main__":
    main()
